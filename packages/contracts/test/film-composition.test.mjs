import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {canonical,digest,parseCanonicalJson,createFilmComposition,filmCompositionErrors,filmBuildReceipt,sourceBuildErrors,
 contentIdentity,artifactIdentity,outputArtifactIdentity,inheritRevisionEnvironment,revisionEnvironmentErrors} from '../index.mjs';
import {semanticErrors} from '../../../scripts/contract-validation.mjs';
import {filmContractFixture} from '../../../tests/contracts/film-fixture.mjs';
const clone=x=>structuredClone(x);

test('film-v1 composition, frozen snapshot, aspect reuse and legacy identity remain connected',()=>{
 const x=filmContractFixture({exampleOnly:false}),{composition:c,context,resourceManifest,factManifest}=x;
 assert.deepEqual(filmCompositionErrors(c,{...context,filmSource:x.filmSource}),[]);
 assert.deepEqual(semanticErrors(c,{...context,newCreativeWrite:true,requireQuality:true}),[]);
 assert.deepEqual(semanticErrors(x.snapshot,context),[]);
 assert.equal(c.identityVersion,2);assert.equal(c.capabilityProfile,'film-v1');assert.equal(c.variants.length,7);
 assert.ok(c.variants.every(v=>v.entrypoint==='film.json'&&v.sourceHash===c.sourceArchiveHash));
 const a=c.variants.find(v=>v.targetId==='x:landscape'),b=c.variants.find(v=>v.targetId==='youtube:landscape');
 assert.equal(digest(artifactIdentity(c,a,x.input.presetConfig)),digest(artifactIdentity(c,b,x.input.presetConfig)));
 assert.equal(digest(outputArtifactIdentity(c,a,'video','marking-v1',x.input.presetConfig)),digest(outputArtifactIdentity(c,b,'video','marking-v1',x.input.presetConfig)));
 assert.notEqual(digest(outputArtifactIdentity(c,a,'mapping','marking-v1',x.input.presetConfig)),digest(outputArtifactIdentity(c,b,'mapping','marking-v1',x.input.presetConfig)));
 const changed=clone(x.film);changed.texts.headline.text='A changed original headline.';
 const edited=createFilmComposition({...x.input,filmSource:canonical(changed),revisionId:'revision_after_edit'});
 assert.notEqual(digest(contentIdentity(c)),digest(contentIdentity(edited)));
 assert.equal(digest(contentIdentity(c)),digest(contentIdentity(createFilmComposition({...x.input,revisionId:'revision_restored'}))));
 const renderer=clone(c);renderer.rendererImageDigest='sha256:'+digest('different image');
 assert.equal(digest(contentIdentity(c)),digest(contentIdentity(renderer)));
 assert.notEqual(digest(artifactIdentity(c,a,x.input.presetConfig)),digest(artifactIdentity(renderer,a,x.input.presetConfig)));
 const confirmation=clone(factManifest);confirmation.facts[0].confirmedBy='different_owner';
 assert.equal(digest(contentIdentity(c)),digest(contentIdentity(createFilmComposition({...x.input,factManifest:confirmation}))));
 assert.deepEqual(sourceBuildErrors(c,context.sourceBuilds,context.sourceArchiveFiles),[]);
 const forged=clone(context.sourceBuilds);forged[c.variants[0].targetId].filmSource=canonical(changed);
 assert.ok(sourceBuildErrors(c,forged,context.sourceArchiveFiles).includes('SOURCE_HASH_MISMATCH'));
 assert.throws(()=>filmBuildReceipt(JSON.stringify(x.film,null,2)),/FILM_SOURCE_NOT_CANONICAL/);
 const missing=clone(factManifest);missing.bindings=[];
 assert.throws(()=>createFilmComposition({...x.input,factManifest:missing}),/FILM_FACT_BINDING_MISSING/);
 const unused=clone(x.film);unused.scenes[2].params.textSlot='headline';
 assert.throws(()=>createFilmComposition({...x.input,filmSource:canonical(unused)}),/FILM_FACT_BINDING_NOT_DRAWN/);
 const wrongAsset=clone(resourceManifest);wrongAsset.resources[0].path='assets/not_the_broker_binding.svg';
 assert.throws(()=>createFilmComposition({...x.input,resourceManifest:wrongAsset}),/FILM_ASSET_RESOURCE_MISSING/);
 const badSnapshot=clone(x.snapshot);badSnapshot.qualityAssociations=[];
 assert.ok(semanticErrors(badSnapshot,context).length>0);
 const pendingRights=clone(context);pendingRights.licenseRegistry={};
 assert.ok(semanticErrors(x.snapshot,pendingRights).includes('LICENSE_RECORD_UNAVAILABLE'));
 const noBuild=clone(context);noBuild.sourceBuilds={};
 assert.ok(semanticErrors(x.snapshot,noBuild).includes('SOURCE_BUILD_REQUIRED'));
 const legacy=parseCanonicalJson(readFileSync(new URL('../../../contracts/composition.example.json',import.meta.url)));
 const oldSnapshot=parseCanonicalJson(readFileSync(new URL('../../../contracts/release-snapshot.example.json',import.meta.url)));
 assert.equal(digest(contentIdentity(legacy)),oldSnapshot.contentHash);
 assert.deepEqual(semanticErrors(legacy),[]);assert.ok(semanticErrors(legacy,{newCreativeWrite:true}).includes('FILM_PROFILE_REQUIRED'));
 const inherited=inheritRevisionEnvironment(c,{...clone(edited),identityVersion:1,capabilityProfile:'wrong',runtimeVersion:'wrong'});
 assert.deepEqual(revisionEnvironmentErrors(c,inherited),[]);
 assert.equal(inherited.identityVersion,2);assert.equal(inherited.capabilityProfile,'film-v1');
});

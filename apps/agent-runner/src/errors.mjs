export function publicErrorCode(error) {
  const candidate=typeof error==='string'?error:typeof error?.code==='string'?error.code:error?.message;
  if(typeof candidate==='string') {
    const code=candidate.split(':',1)[0];
    if(codes.has(code))return code;
    if(/^LOCAL_AGENT_PROVIDER_HTTP_[1-5][0-9]{2}$/.test(code))return code;
  }
  return 'LOCAL_AGENT_OPERATION_FAILED';
}
export function privateErrorDiagnostic(error) {
  const diagnostic={name:String(error?.name??'Error'),message:String(error?.message??error).slice(0,32768)};
  if(error?.code!==undefined)diagnostic.code=String(error.code).slice(0,256);
  if(error?.cause)diagnostic.cause=String(error.cause?.message??error.cause).slice(0,32768);
  if(error?.details!==undefined) {
    try{diagnostic.details=String(JSON.stringify(error.details)).slice(0,32768);}catch{diagnostic.details='Unserializable private diagnostic';}
  }
  return diagnostic;
}

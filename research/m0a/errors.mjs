export function benchmarkErrorCode(error) {
  if(error?.name==='AbortError')return 'M0A_CANCELLED';
  const code=String(error?.code??error?.message??error).split(/[:\s]/u,1)[0];
  if(publicCodes.has(code))return code;
  const agentCode=publicErrorCode(error);return agentCode==='LOCAL_AGENT_OPERATION_FAILED'?'M0A_OPERATION_FAILED':agentCode;
}
export function writePrivateError(file,error) {
  writeFileSync(file,canonical({name:String(error?.name??'Error'),message:String(error?.message??error).slice(0,32768),
    stack:typeof error?.stack==='string'?error.stack.slice(0,32768):null,details:error?.details??null,sandboxState:error?.sandboxState??null})+'\n',{flag:'wx',mode:0o600});
}
